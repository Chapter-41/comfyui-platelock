"""Deterministic, redistributable moving fixtures. No client footage or model needed."""
from fractions import Fraction
from pathlib import Path
import json
import cv2
import numpy as np
from .video import FrameWriter


def moving_plate(n=60, width=320, height=180, seed=41):
    rng=np.random.default_rng(seed)
    background=cv2.GaussianBlur(rng.integers(20,200,(height,width,3),dtype=np.uint8),(3,3),0)
    for _ in range(100):
        x,y=rng.integers([0,0],[width,height]); color=tuple(int(v) for v in rng.integers(30,240,3))
        cv2.circle(background,(int(x),int(y)),int(rng.integers(2,6)),color,-1)
    texture=rng.integers(30,235,(44,44,3),dtype=np.uint8)
    frames=[]
    for i in range(n):
        camera=np.float32([[1,0,3*np.sin(i/13)],[0,1,2*np.cos(i/19)]])
        f=cv2.warpAffine(background,camera,(width,height),borderMode=cv2.BORDER_REFLECT)
        x=int(25+i*2.2)%(width-60);y=int(65+24*np.sin(i/8))
        f[y:y+44,x:x+44]=texture
        cv2.rectangle(f,(x,y),(x+43,y+43),(230,190,60),2)
        frames.append(f)
    return np.stack(frames)


def examples():
    plate=moving_plate()
    matrix=np.float32([[.975,0,7],[0,.975,-3]])
    fixed=np.stack([cv2.warpAffine(f,matrix,(320,180)) for f in plate])
    fixed=np.clip(fixed.astype(float)*[1.04,.97,1.01]+2,0,255).astype(np.uint8)
    truth=[i for i in range(len(plate)) if i not in (20,40)]
    unknown=np.full_like(plate,75)
    return plate,{'framing':fixed,'timing':plate[truth],'unknown':unknown},truth


def write_examples(destination):
    dest=Path(destination);dest.mkdir(parents=True,exist_ok=True)
    plate,cases,truth=examples()
    for name,frames in {'plate':plate,**cases}.items():
        writer=FrameWriter(dest/f'platelock_demo_{name}.mp4',320,180,Fraction(25),'h264')
        try:
            for f in frames: writer.write(f)
        finally: writer.close()
    (dest/'truth.json').write_text(json.dumps({
        'license':'MIT; procedural fixtures generated by PlateLock, not AI generation or client footage',
        'fps':25,'plate_frames':60,'framing':{'scale':.975,'translation':[7,-3]},
        'timing':{'source_indices':truth,'missing':[20,40]},
        'unknown':'Flat image: insufficient shared features, not a clean result.'},indent=2))
    return dest
